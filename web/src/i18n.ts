export type Lang = 'en' | 'pt';
const dicts: Record<Lang, Record<Key, string>> = { en, pt };

function initial(): Lang {
  try {
    const saved = localStorage.getItem('digiisp.lang');
    if (saved === 'en' || saved === 'pt') return saved;
  } catch {
    // storage blocked
  }
  return navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

let current: Lang = initial();
const listeners = new Set<() => void>();

export function lang(): Lang {
  return current;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = dicts[current][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, v) => (v in vars ? String(vars[v]) : m));
}

/** Translate data-i18n* attributes below root. */
export function applyStatic(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle as Key)));
  document.documentElement.lang = current === 'pt' ? 'pt-BR' : 'en';
}

/** Run now and after every language change (to redraw dynamic text). */
export function onLang(fn: () => void) {
  listeners.add(fn);
}

export function setLang(l: Lang) {
  current = l;
  try {
    localStorage.setItem('digiisp.lang', l);
  } catch {
    // storage blocked
  }
  applyStatic();
  listeners.forEach((fn) => fn());
}

/** Fill a language select (top right of the page) and keep it in sync. */
export function languageSelect(sel: HTMLSelectElement) {
  sel.innerHTML = '';
  for (const l of ['en', 'pt'] as Lang[]) sel.add(new Option(dicts[l]['lang.name'], l, false, l === current));
  sel.onchange = () => setLang(sel.value as Lang);
}
